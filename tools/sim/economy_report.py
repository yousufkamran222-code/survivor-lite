#!/usr/bin/env python3
"""Turns economy_sim.gd / campaign_sim.gd JSON into docs/ECONOMY_REPORT.md tables.

Usage: python3 tools/sim/economy_report.py <dir with *_<strategy>.json and campaign_<mode>.json> > docs/ECONOMY_REPORT.md
"""
import glob
import json
import os
import sys

NAMES = {
    "meta_hp": "Max HP", "meta_might": "Damage", "meta_haste": "Weapon speed", "meta_armor": "Resist",
    "meta_regen": "Regen", "meta_move": "Move", "meta_magnet": "Pickup", "meta_growth": "XP", "meta_greed": "Gold",
    "meta_amount": "Extra shots", "meta_dash_cd": "Dash recharge", "meta_dash_charge": "Dash charge",
    "meta_dash_dmg": "Dash dmg", "meta_dash_decoy": "Decoy", "meta_convert": "Convert",
    "meta_evo_bolt": "Evo Storm", "meta_evo_orbit": "Evo Wall", "meta_evo_nova": "Evo Spike", "meta_evo_chain": "Evo Neural",
    "meta_outbreak": "Pandemic",
}


def budget_label(b, full):
    return "full shop (%dk)" % round(full / 1000) if b >= full else ("%dk" % (b // 1000) if b >= 1000 and b % 1000 == 0 else str(b))


def cleared(row, thr=0.5):
    """Highest Virulence level with a win rate >= thr (0 = none)."""
    best = 0
    for c in row["by_v"]:
        if c["win_rate"] >= thr:
            best = c["v"]
    return best


def cell(row, v):
    for c in row["by_v"]:
        if c["v"] == v:
            return "%d%%" % round(c["win_rate"] * 100)
    return "·"


def main(d):
    runs = sorted(glob.glob(os.path.join(d, "*_*.json")))
    eco = {}
    camp = {}
    for p in runs:
        j = json.load(open(p))
        base = os.path.basename(p)
        if base.startswith("campaign_"):
            camp[j["mode"]] = j
        else:
            eco[(j["mode"], j["strategy"])] = j
    out = []
    w = out.append
    any_j = next(iter(eco.values()))
    full = any_j["full_shop"]
    w("# Economy report: what gold buys, and what the bot clears with it")
    w("")
    w("Generated by `tools/sim/economy_sim.gd` + `tools/sim/campaign_sim.gd` (then `tools/sim/economy_report.py`). "
      "%d runs per cell, seed %d. Shop only: no Lab, no ability, no Side Effects (the bot never takes them). "
      "The bot plays very differently from a person (no aiming, random-ish cards), so read win rates as a **shape** "
      "for comparing budgets and modes, not as what a good player will do. A cell is the bot's win rate at that "
      "Virulence; `·` = not run (the climb stops after the first level under 15%%)." % (any_j["runs"], any_j["seed"]))
    w("")
    w("Full shop cost: **%d gold**." % full)
    w("")
    # Strategy comparison (modes that have more than one strategy)
    for mode in sorted({m for (m, s) in eco}):
        strats = [s for (m, s) in eco if m == mode]
        if len(strats) > 1:
            w("## %s: which way of spending gold works best" % mode.capitalize())
            w("")
            w("Highest Virulence the bot wins at least half the time (\"cleared\"), per budget and buying strategy:")
            w("")
            w("| Budget | " + " | ".join(sorted(strats)) + " |")
            w("|---|" + "---|" * len(strats))
            budgets = [r["budget"] for r in eco[(mode, strats[0])]["rows"]]
            for i, b in enumerate(budgets):
                cells = []
                for s in sorted(strats):
                    r = eco[(mode, s)]["rows"][i]
                    cells.append("V%d" % cleared(r) if cleared(r) else "none")
                w("| %s | %s |" % (budget_label(b, full), " | ".join(cells)))
            w("")
            w("*cheapest* = always the next cheapest tier (how many players and the campaign sim buy); *offense* = damage first; "
              "*defense* = survival first; *value* = best power per gold (fixed weights, gold bonus last).")
            w("")
    # Per mode, per strategy: win rate by Virulence
    for (mode, strat), j in sorted(eco.items()):
        w("## %s, %s buyer: win rate by Virulence" % (mode.capitalize(), strat))
        w("")
        vmax = max(c["v"] for r in j["rows"] for c in r["by_v"])
        w("| Budget | Spent | " + " | ".join("V%d" % v for v in range(1, vmax + 1)) + " | Gold/run at the top level |")
        w("|---|---|" + "---|" * vmax + "---|")
        for r in j["rows"]:
            top = r["by_v"][-1]
            w("| %s | %d | %s | %d |" % (budget_label(r["budget"], full), r["spent"],
                                         " | ".join(cell(r, v) for v in range(1, vmax + 1)), top["gold_per_run"]))
        w("")
    # Builds (value buyer, or the first strategy present)
    for mode in sorted({m for (m, s) in eco}):
        key = (mode, "value") if (mode, "value") in eco else next(k for k in eco if k[0] == mode)
        if mode != "classic" and key[1] != "value":
            continue
        if mode != "classic":
            continue  # builds don't depend on the mode
        w("## What each budget buys (%s buyer)" % key[1])
        w("")
        w("Shop tiers owned per upgrade:")
        w("")
        ids = [k for k in NAMES]
        rows = eco[key]["rows"]
        used = [i for i in ids if any(r["levels"].get(i, 0) for r in rows)]
        w("| Budget | " + " | ".join(NAMES[i] for i in used) + " |")
        w("|---|" + "---|" * len(used))
        for r in rows:
            w("| %s | %s |" % (budget_label(r["budget"], full), " | ".join(str(r["levels"].get(i, 0) or "") for i in used)))
        w("")
    # Campaign: how long budgets take
    if camp:
        w("## How long it takes to earn it (fresh account, cheapest buyer, always the highest unlocked Virulence)")
        w("")
        marks = [500, 1000, 2000, 5000, 10000, 20000, 40000]
        w("| Mode | " + " | ".join("%s gold" % budget_label(m, full) for m in marks) + " | First clears (run #) | Hours played |")
        w("|---|" + "---|" * len(marks) + "---|---|")
        for mode, j in sorted(camp.items()):
            cum = 0
            reach = {}
            for r in j["rows"]:
                cum += r["gold"]
                for m in marks:
                    if m not in reach and cum >= m:
                        reach[m] = r["run"]
            fc = ", ".join("V%s@%s" % (k, v) for k, v in sorted(j["first_clear_run"].items(), key=lambda x: int(x[0])))
            w("| %s | %s | %s | %s |" % (mode.capitalize(), " | ".join(("run %d" % reach[m]) if m in reach else "—" for m in marks),
                                       fc or "none", j["hours_played"]))
        w("")
        w("Run numbers count every run (wins and losses). Gold includes no ads (a doubled-gold ad would roughly halve these).")
        w("")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
